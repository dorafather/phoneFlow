    /** sigunguName과 이름이 일치하는 모든 후보(동명이지 지역 포함)를 돌려준다. */
    fun candidatesFor(sigunguName: String): List<EvRegionMatch> =
        ZSCODE_TABLE.filter { it.first == sigunguName }.map { (name, zscode) ->
            val zcode = zscode.take(2)
            EvRegionMatch(
                sigunguName = name,
                zcode = zcode,
                zscode = zscode,
                sidoName = ZCODE_TO_SIDO[zcode].orEmpty()
            )
        }

    /** Geocoder가 돌려준 시/도 이름(adminArea)과 후보의 zcode 소속 시도가 같은지 확인한다. */
    fun matchesSido(match: EvRegionMatch, geocoderSidoName: String): Boolean {
        if (geocoderSidoName.isBlank()) return false
        if (match.sidoName.isNotEmpty() &&
            (geocoderSidoName.startsWith(match.sidoName) || match.sidoName.startsWith(geocoderSidoName))
        ) {
            return true
        }
        return ZCODE_ALT_SIDO_NAMES[match.zcode]?.any { alt ->
            geocoderSidoName.startsWith(alt) || alt.startsWith(geocoderSidoName)
        } == true
    }
